// SeedDemoData seeds the library with a realistic, high-signal multi-horizon showcase dataset in the specified or workspace locale.
func (s *Service) SeedDemoData(ctx context.Context, optLocale ...string) error {
	if s.Store == nil {
		return fmt.Errorf("seed: store not configured")
	}

	targetLocale := ""
	if len(optLocale) > 0 && optLocale[0] != "" {
		targetLocale = optLocale[0]
	} else {
		if loc, err := s.Store.GetSetting(ctx, "interface_locale"); err == nil && loc != "" {
			targetLocale = loc
		}
	}
	if !port.IsValidInterfaceLocale(targetLocale) {
		targetLocale = port.DefaultInterfaceLocale
	}

	ds := getDemoDataset(targetLocale)
	now := time.Now().UTC()

	var researchCardID int64
	for i, c := range ds.cards {
		card := port.Card{
			Title:            c.Title,
			Summary:          c.Summary,
			Horizon:          c.Horizon,
			Status:           c.Status,
			Type:             c.Type,
			SourceURL:        c.SourceURL,
			SourceNote:       c.SourceNote,
			TLDR:             c.TLDR,
			WhyCare:          c.WhyCare,
			Claims:           c.Claims,
			OpenQuestions:    c.OpenQuestions,
			Worthiness:       port.Worthiness{Level: c.WorthinessLevel, Reason: c.WorthinessReason},
			SuggestedHorizon: c.SuggestedHorizon,
			SuggestedTags:    c.SuggestedTags,
			ExecutiveSummary: c.ExecutiveSummary,
			ValueProposition: c.ValueProposition,
			ProposedActions:  c.ProposedActions,
			CompletedActions: c.CompletedActions,
			Tags:             c.Tags,
		}
		if c.ResearchVerdict != "" {
			card.ResearchVerdict = c.ResearchVerdict
			card.ResearchConfidence = c.ResearchConf
		}

		created, err := s.Store.CreateCard(ctx, card)
		if err == nil && i == 4 { // Research card
			researchCardID = created.ID
		}
	}

	if researchCardID > 0 {
		r, rerr := s.Store.CreateResearch(ctx, researchCardID, ds.dossier.Title)
		if rerr == nil {
			_, _ = s.Store.SetResearch(ctx, r.ID, "done", ds.dossier.Findings, "")
			steps := []port.ResearchStep{
				{ID: "step-1", Status: "done", StartedAt: now, FinishedAt: now, Note: ds.dossier.Step1Note},
				{ID: "step-2", Status: "done", StartedAt: now, FinishedAt: now, Note: ds.dossier.Step2Note},
				{ID: "step-3", Status: "done", StartedAt: now, FinishedAt: now, Note: ds.dossier.Step3Note},
			}
			resResult := &port.ResearchResult{
				Verdict: &port.ResearchVerdict{
					Recommendation: "pursue",
					Confidence:     "high",
					ForWhom:        ds.dossier.ForWhom,
					Risks:          ds.dossier.Risks,
					NextActions:    ds.dossier.NextActions,
				},
			}
			_ = s.Store.UpdateResearchProgress(ctx, r.ID, "done", ds.dossier.Title, steps, nil, nil, resResult, 1500)
		}
	}

	return nil
}
